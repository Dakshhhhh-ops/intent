import type { Analysis, Claim, Trace } from '../types';
import { RULE_INFO } from '../analyze/rules';
import { truncate } from '../util';

// PR-ready Markdown. Paste it into a pull request, or let `intent-replay report` print it.

const VERDICT_ICON: Record<Claim['verdict'], string> = {
  supported: '✅ Supported',
  contradicted: '❌ Contradicted',
  stale: '⚠️ Stale',
  unverified: '❔ Unverified',
};

const SEV_ICON = { high: '🔴', medium: '🟠', low: '🔵', info: '⚪' } as const;

export function formatDuration(ms: number | null): string {
  if (ms === null || ms < 0) return '—';
  const s = Math.round(ms / 1000);
  if (s < 60) return `${s}s`;
  const m = Math.floor(s / 60);
  if (m < 60) return `${m}m ${s % 60}s`;
  return `${Math.floor(m / 60)}h ${m % 60}m`;
}

export function toMarkdown(trace: Trace, a: Analysis, opts: { link?: string } = {}): string {
  const st = a.stats;
  const out: string[] = [];
  const icon = a.verdict.level === 'risky' ? '🔴' : a.verdict.level === 'review' ? '🟠' : '🟢';
  out.push(`## ${icon} Intent Replay: ${a.verdict.label}`);
  out.push('');
  out.push(`**Task:** ${truncate(trace.title, 200)}`);
  out.push('');
  out.push(
    `${trace.agentVersion ?? trace.source}${trace.model ? ` · ${trace.model}` : ''} · ${formatDuration(st.durationMs)} · ${st.steps} steps · ` +
      `${plural(st.filesChanged, 'file')} changed (+${st.linesAdded} −${st.linesRemoved}) · ${plural(st.commands, 'command')} (${st.commandsFailed} failed)`,
  );
  out.push('');
  out.push(`> ${a.verdict.summary}`);
  out.push('');

  if (a.claims.length) {
    out.push('### Claim check');
    out.push('');
    out.push('| The agent said | Verdict | Evidence |');
    out.push('|---|---|---|');
    for (const c of a.claims) {
      const ev = c.caveat ? `${c.explanation} ${c.caveat}` : c.explanation;
      out.push(`| ${cell(c.text)} | ${VERDICT_ICON[c.verdict]} | ${cell(ev)} |`);
    }
    out.push('');
  }

  if (a.findings.length) {
    out.push('### Findings');
    out.push('');
    for (const f of a.findings) {
      out.push(`- ${SEV_ICON[f.severity]} **${f.title}** — ${f.detail} _(${RULE_INFO[f.rule].name}; steps ${f.steps.map((s) => s + 1).join(', ')})_`);
    }
    out.push('');
  }

  if (a.files.length) {
    out.push('### Files changed');
    out.push('');
    out.push('| File | +/− | Edits | Read first? | Notes |');
    out.push('|---|---|---|---|---|');
    for (const f of a.files) {
      const readFirst = f.created ? 'new file' : f.reads.length && f.reads[0] < f.edits[0] ? 'yes' : '**no**';
      out.push(`| \`${f.path}\` | +${f.added} −${f.removed} | ${f.edits.length} | ${readFirst} | ${f.flags.join(', ') || ''} |`);
    }
    out.push('');
  }

  if (a.phases.length) {
    out.push('<details><summary>How the run unfolded</summary>');
    out.push('');
    a.phases.forEach((p, i) => {
      out.push(`${i + 1}. **${cap(p.kind)}** (steps ${p.from + 1}–${p.to + 1}): ${p.summary}`);
    });
    out.push('');
    out.push('</details>');
    out.push('');
  }

  out.push(`<sub>Generated by Intent Replay from the agent's own session log${opts.link ? ` · [open the replay](${opts.link})` : ''}. Secrets are masked.</sub>`);
  return out.join('\n');
}

function plural(n: number, w: string): string {
  return `${n} ${w}${n === 1 ? '' : 's'}`;
}

function cell(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function cap(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}
